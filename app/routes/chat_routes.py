"""
Chat & Dialogue Routes Blueprint for DevKnow.

Provides conversational AI and Retrieval-Augmented Generation (RAG) endpoints:
1. `POST /api/chat`:
   Streaming conversational endpoint using Server-Sent Events (SSE).
   Streams metadata (grounding stats, retrieved functions, thinking steps),
   token chunks, and a completion event.
2. `GET /api/conversations`:
   Lists recent chat conversation sessions.
3. `GET /api/conversations/<session_id>`:
   Retrieves all messages and attached code snippets for a specific session.
4. `DELETE /api/conversations/<session_id>`:
   Deletes a conversation session and all its messages.
"""

import json
import uuid
import logging
from flask import Blueprint, request, Response, stream_with_context, jsonify

from app.services.mysql_service import db_service
from app.services.retrieval_service import RetrievalService
from app.services.gemini_service import gemini_service
from app.models.database_models import Conversation, ConversationMessage

chat_bp = Blueprint("chat", __name__)
logger = logging.getLogger("DevKnow.ChatRoutes")


@chat_bp.route("/chat", methods=["POST"])
def chat():
    """
    RAG Chat endpoint with real-time Server-Sent Events (SSE) streaming.

    SSE Event Lifecycle:
    1. `event: metadata`:
       Emits retrieval details, candidate match score, ground truth attribution
       percentages, and multi-step UI reasoning disclosure ('thinking_steps').
    2. `event: token`:
       Streams individual markdown tokens as they are generated by the LLM.
    3. `event: done`:
       Signals completion of the stream and confirms session persistence.

    JSON Payload:
        - query: Natural language user question or instruction (required).
        - session_id: (Optional) Conversation UUID. Auto-generated if omitted.
        - selected_language: (Optional) Active language filter dropdown in UI.
        - attached_code: (Optional) Code snippet attached for review/conversion.

    Responses:
        200: text/event-stream Response object.
        400: Empty query or query exceeding character limit.
    """
    data = request.get_json() or {}
    query = data.get("query", "").strip()
    session_id = data.get("session_id", "").strip()
    selected_language = data.get("selected_language", None)
    attached_code = data.get("attached_code", None)

    # Input guardrail checks
    if not query:
        return jsonify({"success": False, "error": "Query cannot be empty"}), 400

    if len(query) > 4000:
        return jsonify({"success": False, "error": "Query exceeds maximum limit of 4000 characters"}), 400

    if not session_id:
        session_id = str(uuid.uuid4())

    # Ensure conversation session exists and persist user message
    with db_service.get_session() as session:
        conv = session.query(Conversation).filter_by(session_id=session_id).first()
        if not conv:
            title = query[:50] + ("..." if len(query) > 50 else "")
            conv = Conversation(session_id=session_id, title=title)
            session.add(conv)
            session.flush()

        conv_id = conv.id

        user_msg = ConversationMessage(
            conversation_id=conv_id,
            role="user",
            message=query,
            attached_code=attached_code,
            answer_source="none"
        )
        session.add(user_msg)

    # Execute RAG Retrieval, grounding verification, and prompt assembly
    rag_result = RetrievalService.execute_rag(
        query=query,
        session_id=session_id,
        selected_language=selected_language,
        attached_code=attached_code
    )

    prompt = rag_result["prompt"]
    source = rag_result["source"]
    intent = rag_result["intent"]
    max_score = rag_result["max_score"]
    retrieved_functions = rag_result["retrieved_functions"]

    def generate_stream():
        # 1. Emit metadata event with grounding stats and thinking steps
        meta_payload = {
            "session_id": session_id,
            "source": source,
            "intent": intent,
            "similarity_score": max_score,
            "retrieved_count": len(retrieved_functions),
            "retrieved_functions": retrieved_functions,
            "thinking_steps": rag_result.get("thinking_steps", []),
            "grounding_stats": rag_result.get("grounding_stats", {}),
            "latency_ms": rag_result.get("execution_metadata", {}).get("latency_ms", 0)
        }
        yield f"event: metadata\ndata: {json.dumps(meta_payload)}\n\n"

        # 2. Stream tokens from the LLM
        full_response_text = []
        try:
            for token in gemini_service.stream_generate(prompt):
                full_response_text.append(token)
                token_data = json.dumps({"token": token})
                yield f"event: token\ndata: {token_data}\n\n"
        except Exception as e:
            logger.exception(f"Unhandled exception during stream generation: {e}")
            fallback_text = "\n\nI encountered an unexpected issue while generating this response. Please try again."
            err_data = json.dumps({"token": fallback_text})
            yield f"event: token\ndata: {err_data}\n\n"

        complete_text = "".join(full_response_text)

        # 3. Save assistant message to conversation history
        try:
            with db_service.get_session() as session:
                assistant_msg = ConversationMessage(
                    conversation_id=conv_id,
                    role="assistant",
                    message=complete_text,
                    answer_source=source,
                    retrieved_function_ids=",".join(str(f["id"]) for f in retrieved_functions),
                    similarity_score=max_score,
                    query_intent=intent
                )
                session.add(assistant_msg)
        except Exception as ex:
            logger.error(f"Failed to record assistant message in DB: {ex}")

        # 4. Emit done event
        yield f"event: done\ndata: {json.dumps({'status': 'finished', 'session_id': session_id})}\n\n"

    return Response(
        stream_with_context(generate_stream()),
        mimetype="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "X-Accel-Buffering": "no",
            "Connection": "keep-alive"
        }
    )


@chat_bp.route("/conversations", methods=["GET"])
def list_conversations():
    """
    Returns the 20 most recent conversation sessions.

    Responses:
        200: JSON list of Conversation records.
    """
    with db_service.get_session() as session:
        convs = session.query(Conversation).order_by(Conversation.updated_at.desc()).limit(20).all()
        return jsonify({
            "success": True,
            "conversations": [c.to_dict() for c in convs]
        })


@chat_bp.route("/conversations/<session_id>", methods=["GET"])
def get_conversation(session_id: str):
    """
    Retrieves all messages and context for a specific chat session.

    Path Parameters:
        session_id: UUID of the conversation session.

    Responses:
        200: JSON object containing conversation metadata and list of messages.
    """
    with db_service.get_session() as session:
        conv = session.query(Conversation).filter_by(session_id=session_id).first()
        if not conv:
            return jsonify({
                "success": True,
                "conversation": None,
                "messages": []
            }), 200

        messages = [m.to_dict() for m in conv.messages]
        return jsonify({
            "success": True,
            "conversation": conv.to_dict(),
            "messages": messages
        })


@chat_bp.route("/conversations/<session_id>", methods=["DELETE"])
def delete_conversation(session_id: str):
    """
    Deletes a conversation session and cascades deletion to all associated messages.

    Path Parameters:
        session_id: UUID of the conversation session.

    Responses:
        200: Deletion confirmation.
    """
    with db_service.get_session() as session:
        conv = session.query(Conversation).filter_by(session_id=session_id).first()
        if not conv:
            return jsonify({
                "success": True,
                "conversation": None,
                "messages": []
            }), 200

        session.delete(conv)
        return jsonify({"success": True, "message": "Conversation deleted successfully."})
